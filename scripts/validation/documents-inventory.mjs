#!/usr/bin/env node
/**
 * Writes docs/documents-inventory.md: every downloadable document linked from the site
 * (PDF, spreadsheets, ZIP, Word…), where it is stored and which pages link to it.
 * Classification (Phase 12 of the migration spec):
 *   A hosted by the site (copied into public/, same URL as before)
 *   B intentionally external (hosted by UPM or other institutions)
 *   C obsolete / broken (could not be retrieved)
 *   D generated dynamically
 * Usage: npm run build && npm run docs:documents   (add --external to check external documents)
 */
import fs from 'node:fs';
import path from 'node:path';
import * as cheerio from 'cheerio';
import { ROOT } from '../build/data.mjs';

const DIST = path.join(ROOT, 'dist');
const DOC = /\.(pdf|docx?|xlsx?|pptx?|odt|ods|zip|rtf)$/i;
const MIME = { pdf: 'application/pdf', xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', xls: 'application/vnd.ms-excel', zip: 'application/zip', docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', doc: 'application/msword' };
const site = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'site.json'), 'utf8'));
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const docs = new Map();
for (const f of walk(DIST).filter((x) => x.endsWith('.html'))) {
  const page = '/' + path.relative(DIST, f).replace(/\\/g, '/').replace(/index\.html$/, '');
  const $ = cheerio.load(fs.readFileSync(f, 'utf8'));
  $('a[href]').each((_, a) => {
    const href = $(a).attr('href');
    let u; try { u = new URL(href, 'http://local'); } catch { return; }
    if (!DOC.test(decodeURIComponent(u.pathname))) return;
    const key = u.host === 'local' ? u.pathname : u.href;
    if (!docs.has(key)) docs.set(key, { key, local: u.host === 'local', pages: new Set(), labels: new Set() });
    docs.get(key).pages.add(page);
    const label = $(a).text().replace(/\s+/g, ' ').trim(); if (label) docs.get(key).labels.add(label);
  });
}
const checkExternal = process.argv.includes('--external');
const rows = [];
for (const d of [...docs.values()].sort((a, b) => Number(b.local) - Number(a.local) || a.key.localeCompare(b.key))) {
  const ext = path.extname(decodeURIComponent(d.key)).slice(1).toLowerCase();
  let status, localFile = '', size = '';
  if (d.local) {
    const file = path.join(ROOT, 'public', decodeURIComponent(d.key));
    const ok = fs.existsSync(file);
    status = ok ? 'A – hosted by the site (migrated, URL unchanged)' : 'C – MISSING';
    localFile = ok ? `public${decodeURIComponent(d.key)}` : '';
    size = ok ? `${Math.round(fs.statSync(file).size / 1024)} KB` : '';
  } else {
    status = 'B – intentionally external';
    if (checkExternal) {
      try { const r = await fetch(d.key, { method: 'HEAD', redirect: 'follow', signal: AbortSignal.timeout(20000) }); status += ` (HTTP ${r.status})`; if (r.status >= 400) status = `C – broken external document (HTTP ${r.status})`; }
      catch (e) { status += ` (not reachable: ${e.cause?.code || e.message})`; }
    }
  }
  rows.push({ ...d, ext, status, localFile, size, source: d.local ? site.siteUrl + d.key : d.key });
}
let md = `# Downloadable documents inventory\n\nGenerated by \`npm run docs:documents\` from the built site on ${new Date().toISOString().slice(0, 10)}.\n\n`;
md += `Local documents keep the exact URL they had on the WordPress site (\`/wp-content/uploads/sites/8/…\`), so links shared elsewhere keep working; they are stored in \`public/wp-content/uploads/\` and contain nothing that depends on WordPress. No document is generated dynamically (class D: none).\n\n`;
md += `- Documents hosted by the site: ${rows.filter((r) => r.local).length}\n- External documents (UPM and others): ${rows.filter((r) => !r.local).length}\n\n`;
md += '| Document (link text) | Source URL | Local file | Type | Size | Status | Linked from |\n|---|---|---|---|---|---|---|\n';
for (const r of rows) md += `| ${[...r.labels].join(' / ').replace(/\|/g, '\\|')} | ${r.source} | ${r.localFile ? '`' + r.localFile + '`' : '–'} | ${MIME[r.ext] || r.ext} | ${r.size} | ${r.status} | ${[...r.pages].join('<br>')} |\n`;
fs.writeFileSync(path.join(ROOT, 'docs', 'documents-inventory.md'), md);
console.log(`${rows.length} documents (${rows.filter((r) => r.local).length} local) → docs/documents-inventory.md`);
