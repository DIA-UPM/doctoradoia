#!/usr/bin/env node
/**
 * ONE-OFF MIGRATION TOOL: copies the crawled files the static site needs into public/.
 *   - images and documents referenced by the content (.cache/import/assets.json,
 *     filled by generate-page / extract-meta)
 *   - fonts and images referenced by the migrated CSS (.cache/import/css-assets.json)
 *   - header/footer/head assets and the homepage background video (listed below)
 * Prints a summary; every file it copies is listed in docs/assets-inventory.md.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')), '..', '..');
const report = JSON.parse(fs.readFileSync(path.join(ROOT, '.cache/crawl/report.json'), 'utf8'));
const content = JSON.parse(fs.readFileSync(path.join(ROOT, '.cache/import/assets.json'), 'utf8'));
const css = JSON.parse(fs.readFileSync(path.join(ROOT, '.cache/import/css-assets.json'), 'utf8'));

const U = 'https://doctoradoia.dia.fi.upm.es/wp-content/uploads/sites/8/';
const layout = {
  '/assets/images/Logo-conjunto-dia-ets-upm5x.svg': U + '2023/11/Logo-conjunto-dia-ets-upm5x.svg',
  '/assets/images/logo-dia-actualizado.svg': U + '2023/12/logo-dia-actualizado.svg',
  '/assets/images/logo_i2tech.png': 'https://www.fi.upm.es/web/futuroalumno/wp-content/uploads/sites/15/2015/11/logo_i2tech.png',
  '/assets/video/Video-portada-Doctorado-bola-4.mp4': U + '2023/11/Video-portada-Doctorado-bola-4.mp4',
  '/assets/images/portada-doctorado-movil-scaled.jpg': U + '2023/12/portada-doctorado-movil-scaled.jpg',
};

const rows = [];
const copy = (local, src, kind) => {
  const r = report.resources[src];
  const file = r?.file || (typeof src === 'string' && fs.existsSync(path.join(ROOT, src)) ? src : null);
  if (!file) { console.warn('missing in crawl cache:', src); rows.push({ local, src, kind, status: 'MISSING' }); return; }
  const dest = path.join(ROOT, 'public', local);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(path.join(ROOT, file), dest);
  rows.push({ local, src: r ? src : src, kind, bytes: fs.statSync(dest).size, status: 'copied' });
};
for (const [local, v] of Object.entries(content)) copy(local, v.source, /^\/wp-content\//.test(local) ? 'document' : 'content image');
for (const [local, file] of Object.entries(css)) {
  const src = Object.values(report.resources).find((x) => x.file === file)?.url || file;
  copy(local, src, /\/fonts\//.test(local) ? 'font' : 'css image');
}
for (const [local, src] of Object.entries(layout)) copy(local, src, 'layout');

let md = '# Assets inventory\n\nGenerated by `scripts/import/import-assets.mjs`. Every file below lives in `public/` and is copied to `dist/` by the build.\n\n| Local path | Kind | Source | Bytes | Status |\n|---|---|---|---|---|\n';
for (const r of rows.sort((a, b) => a.local.localeCompare(b.local))) md += `| \`${r.local}\` | ${r.kind} | ${r.src} | ${r.bytes ?? ''} | ${r.status} |\n`;
fs.writeFileSync(path.join(ROOT, 'docs', 'assets-inventory.md'), md);
const by = rows.reduce((a, r) => ((a[r.kind] = (a[r.kind] || 0) + 1), a), {});
console.log('assets:', by, 'missing:', rows.filter((r) => r.status !== 'copied').length);
