#!/usr/bin/env node
/**
 * Accessibility comparison: runs axe-core (WCAG 2.1 A/AA rules) on every page of the live
 * site and of the local build, and writes docs/accessibility-report.md.
 * The migration must not make accessibility worse: the script fails if the local build has
 * more violating elements than the live page for any axe rule.
 * Usage: npm run build && npm run test:a11y   (live results are cached in .cache/a11y-live.json; --refresh to re-test the live site)
 */
import '../../scripts/lib/env.mjs';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
import { AxeBuilder } from '@axe-core/playwright';
import { ALL_URLS, LIVE_ORIGIN } from '../helpers/pages.mjs';
import { startServer } from '../../scripts/build/serve.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')), '..', '..');
const CACHE = path.join(ROOT, '.cache', 'a11y-live.json');
const PORT = 8093;
const TAGS = ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'];

async function audit(browser, url) {
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await ctx.newPage();
  for (let attempt = 1; ; attempt++) {
    try { await page.goto(url, { waitUntil: 'load', timeout: 90000 }); break; } catch (e) { if (attempt >= 3) throw e; await new Promise((r) => setTimeout(r, 5000 * attempt)); }
  }
  // final state of entrance animations, like a visitor who scrolled through the page
  await page.evaluate(async () => { for (let y = 0; y < document.body.scrollHeight; y += 500) { window.scrollTo(0, y); await new Promise((r) => setTimeout(r, 30)); } window.scrollTo(0, 0); });
  await page.waitForTimeout(1500);
  const res = await new AxeBuilder({ page }).withTags(TAGS).exclude('#block-64 iframe').analyze();
  await ctx.close();
  return Object.fromEntries(res.violations.map((v) => [v.id, { impact: v.impact, help: v.help, count: v.nodes.length }]));
}

const refresh = process.argv.includes('--refresh');
const live = !refresh && fs.existsSync(CACHE) ? JSON.parse(fs.readFileSync(CACHE, 'utf8')) : {};
const server = await startServer({ port: PORT });
const browser = await chromium.launch();
const rows = [];
let worse = 0;
for (const e of ALL_URLS) {
  if (!live[e.path]) { live[e.path] = await audit(browser, LIVE_ORIGIN + e.path); fs.mkdirSync(path.dirname(CACHE), { recursive: true }); fs.writeFileSync(CACHE, JSON.stringify(live, null, 2)); }
  const local = await audit(browser, `http://localhost:${PORT}${e.path}`);
  for (const id of new Set([...Object.keys(live[e.path]), ...Object.keys(local)])) {
    const a = live[e.path][id]?.count || 0, b = local[id]?.count || 0;
    if (b > a) worse++;
    rows.push({ page: `${e.lang} ${e.path}`, id, impact: (local[id] || live[e.path][id]).impact, help: (local[id] || live[e.path][id]).help, live: a, local: b });
  }
  process.stdout.write('.');
}
await browser.close(); server.close();
let md = `# Accessibility report\n\naxe-core (${TAGS.join(', ')}) on every page at 1440×900, live site vs local build, generated by \`npm run test:a11y\` on ${new Date().toISOString().slice(0, 10)}. Numbers are violating elements per rule (the Google Maps iframe is excluded).\n\n`;
md += `- Rules where the local build is **worse** than the live site: **${worse}**\n- Rules where it is better: ${rows.filter((r) => r.local < r.live).length}\n\n`;
md += '| Page | Rule | Impact | Live | Local | Description |\n|---|---|---|---|---|---|\n' + rows.map((r) => `| ${r.page} | ${r.id} | ${r.impact} | ${r.live} | ${r.local}${r.local > r.live ? ' ⚠' : r.local < r.live ? ' ✓' : ''} | ${r.help} |`).join('\n') + '\n';
fs.writeFileSync(path.join(ROOT, 'docs', 'accessibility-report.md'), md);
console.log(`\n${worse ? '✗' : '✓'} ${worse} rule(s) worse than the live site; report in docs/accessibility-report.md`);
process.exit(worse ? 1 : 0);
